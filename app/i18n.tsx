export type Strings = typeof STRINGS.en;

interface LanguageContextValue { lang: Lang; setLang: (l: Lang) => void; t: Strings }
const LanguageContext = createContext<LanguageContextValue | null>(null);

function readInitialLang(): Lang {
 if (typeof window === 'undefined') return 'vi';
 try { const stored = window.localStorage.getItem(STORAGE_KEY); if (stored === 'en' || stored === 'vi') return stored; } catch { /* localStorage unavailable */ }
 return 'vi';
}

export function LanguageProvider({children}: {children: React.ReactNode}) {
 const [lang, setLangState] = useState<Lang>(readInitialLang);
 useEffect(() => { document.documentElement.lang = lang; try { window.localStorage.setItem(STORAGE_KEY, lang); } catch { /* localStorage unavailable */ } }, [lang]);
 const setLang = (l: Lang) => setLangState(l);
 const value = useMemo(() => ({lang, setLang, t: STRINGS[lang]}), [lang]);
 return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
 const ctx = useContext(LanguageContext);
 if (!ctx) throw new Error('useLanguage must be used within a LanguageProvider');
 return ctx;
}
